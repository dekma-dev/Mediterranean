#include "tools/ObjImport.h"
#include <Windows.h>
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <limits>
#include <locale>
#include <sstream>
#include <stdexcept>

int wmain(int argc,wchar_t** argv) {
  if(argc!=4) { std::cerr<<"Usage: MeshAssetCompiler <input.obj> <output.h> <symbol>\n"; return 2; }
  try {
    const std::filesystem::path source(argv[1]),destination(argv[2]);
    const auto temporary=std::filesystem::path(destination.wstring()+L".tmp");
    const auto sameFile=[](const std::filesystem::path& a,const std::filesystem::path& b) {
      const auto left=std::filesystem::absolute(a).lexically_normal().wstring();
      const auto right=std::filesystem::absolute(b).lexically_normal().wstring();
      std::error_code error;
      return CompareStringOrdinal(left.c_str(),-1,right.c_str(),-1,TRUE)==CSTR_EQUAL ||
        std::filesystem::equivalent(a,b,error);
    };
    if(sameFile(source,destination) || sameFile(source,temporary))
      throw std::runtime_error("Source must differ from destination and temporary output");
    const std::wstring name(argv[3]);
    const auto letter=[](wchar_t c) {return (c>=L'a' && c<=L'z') || (c>=L'A' && c<=L'Z');};
    if(name.empty() || name.size()>64 || !letter(name.front())) throw std::runtime_error("Invalid asset symbol");
    for(auto c:name) if(!letter(c) && !(c>=L'0' && c<=L'9') && c!=L'_') throw std::runtime_error("Invalid asset symbol");
    std::string symbol;
    for(auto c:name) symbol.push_back(static_cast<char>(c)); // Validated ASCII above.
    assets::ObjLimits limits;
    limits.coordinate=.5001f; // Current reusable equipment slots use a unit box.
    limits.triangles=4096; limits.vertices=8192;
    // The anatomical near head has a separate budget from reusable props.
    if(name==L"PlayerHead")limits.triangles=10000;
    const auto size=std::filesystem::file_size(source);
    if(size>limits.bytes) throw std::runtime_error("OBJ exceeds the source byte budget");
    std::ifstream file(source,std::ios::binary);
    std::string content(std::size_t(size),'\0');
    if(!file.read(content.data(),std::streamsize(size))) throw std::runtime_error("Cannot read OBJ source");
    if(file.peek()!=std::char_traits<char>::eof()) throw std::runtime_error("OBJ changed while being read; rebuild again");
    const auto mesh=assets::ImportObj(content,limits);
    std::ostringstream output; output.imbue(std::locale::classic());
    output<<std::scientific<<std::setprecision(std::numeric_limits<float>::max_digits10);
    // Large initializer-list temporaries can exhaust the caller's Windows
    // stack during renderer startup. Store immutable mesh data in static
    // storage and copy directly into the owning vectors.
    output<<"// Generated by MeshAssetCompiler. Edit the source OBJ instead.\n#pragma once\n#include \"engine/Geometry.h\"\nnamespace compiled_mesh {\ninline visual::Geometry "<<symbol<<"() {\nstatic const visual::Vertex vertices[]={\n";
    for(const auto& v:mesh.vertices) {
      output<<"{{"<<v.position.x<<"f,"<<v.position.y<<"f,"<<v.position.z<<"f},{"
        <<v.normal.x<<"f,"<<v.normal.y<<"f,"<<v.normal.z<<"f},{"
        <<v.color.x<<"f,"<<v.color.y<<"f,"<<v.color.z<<"f,"<<v.color.w<<"f}},\n";
    }
    output<<"};\nstatic const std::uint32_t indices[]={\n";
    for(std::size_t i=0;i<mesh.indices.size();++i) {output<<mesh.indices[i]<<',';if(i%24==23) output<<'\n';}
    output<<"\n};\nvisual::Geometry result;\nresult.vertices.assign(vertices,vertices+"<<mesh.vertices.size()
      <<");\nresult.indices.assign(indices,indices+"<<mesh.indices.size()<<");\nreturn result;\n}\n}\n";
    std::ofstream generated(temporary,std::ios::binary|std::ios::trunc);
    generated<<output.str(); generated.close();
    if(!generated) throw std::runtime_error("Cannot write generated mesh header");
    if(!MoveFileExW(temporary.c_str(),destination.c_str(),MOVEFILE_REPLACE_EXISTING|MOVEFILE_WRITE_THROUGH))
      throw std::runtime_error("Cannot replace mesh header: "+std::to_string(GetLastError()));
    std::cout<<symbol<<": "<<mesh.vertices.size()<<" vertices, "<<mesh.indices.size()/3<<" triangles\n";
    return 0;
  } catch(const std::exception& error) {std::cerr<<error.what()<<'\n';return 1;}
}
