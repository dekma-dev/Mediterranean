#include "engine/SceneShader.h"
#include <d3dcompiler.h>
#include <wrl/client.h>
#include <cstring>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <sstream>
#include <stdexcept>

// Compile once during the native build. No shader files are loaded or compiled
// by the game at launch; build failures cannot silently select stale bytecode.
int wmain(int argc,wchar_t** argv) {
  if(argc!=2) { std::cerr<<"Usage: SceneShaderCompiler <generated-header>\n"; return 2; }
  try {
    std::ostringstream output;
    output<<"// Generated by SceneShaderCompiler. Do not edit.\n#pragma once\n#include <cstddef>\nnamespace compiled_scene {\n"
      "struct Bytecode { const unsigned char* data; std::size_t size;\n"
      " const void* GetBufferPointer() const { return data; }\n"
      " std::size_t GetBufferSize() const { return size; } };\n";
    constexpr const char* entries[]={"VSMain","PSMain","VSWorld","VSShadow","VSBody","VSBodyShadow", "VSHand","VSHandShadow","VSSky","PSSky","VSEffect","PSEffect"};
    for(const char* entry : entries) {
      Microsoft::WRL::ComPtr<ID3DBlob> code,errors;
      const HRESULT result=D3DCompile(sceneShader,std::strlen(sceneShader),"BuiltInScene",nullptr,nullptr,entry,
        entry[0]=='V'?"vs_5_0":"ps_5_0",D3DCOMPILE_ENABLE_STRICTNESS,0,&code,&errors);
      if(errors && errors->GetBufferSize()>1) std::cerr<<entry<<": "<<static_cast<const char*>(errors->GetBufferPointer())<<'\n';
      if(FAILED(result) || (errors && errors->GetBufferSize()>1)) throw std::runtime_error(std::string("Shader compilation failed: ")+entry);
      output<<"inline constexpr unsigned char bytes_"<<entry<<"[]={\n";
      const auto bytes=static_cast<const unsigned char*>(code->GetBufferPointer());
      for(std::size_t i=0;i<code->GetBufferSize();++i) {
        output<<unsigned(bytes[i])<<',';
        if(i%32==31) output<<'\n';
      }
      output<<"\n};\ninline constexpr Bytecode "<<entry<<"{bytes_"<<entry<<",sizeof(bytes_"<<entry<<")};\n";
      std::cout<<"Compiled "<<entry<<": "<<code->GetBufferSize()<<" bytes\n";
    }
    output<<"}\n";
    const std::filesystem::path destination(argv[1]),temporary=destination.wstring()+L".tmp";
    std::ofstream file(temporary,std::ios::binary|std::ios::trunc);
    file<<output.str(); file.close();
    if(!file) throw std::runtime_error("Cannot write generated shader header");
    // Publish only after every shader compiled and the complete output closed.
    if(!MoveFileExW(temporary.c_str(),destination.c_str(),MOVEFILE_REPLACE_EXISTING|MOVEFILE_WRITE_THROUGH))
      throw std::runtime_error("Cannot replace generated shader header: "+std::to_string(GetLastError()));
    return 0;
  } catch(const std::exception& error) { std::cerr<<error.what()<<'\n'; return 1; }
}
